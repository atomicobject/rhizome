func ensureIdentifierBackedBlockID(snapshot *DocumentSnapshot, projection *NodeProjection, preferred string) (string, bool, error) {
	if projection == nil || projection.Ref.Kind != NodeKindEmbedded || projection.Type == nil {
		return "", false, nil
	}
	field := preferredBlockIdentifierField(projection.Type)
	if field == nil || field.SourceKind != FieldSourceInline {
		return "", false, nil
	}
	blockID := strings.TrimSpace(strings.TrimPrefix(preferred, "^"))
	if blockID == "" {
		blockID = GenerateBlockIDForProjection(snapshot, projection)
	}
	blockID = BlockSafeIdentifier(blockID)
	if !ValidBlockID(blockID) {
		return "", false, fmt.Errorf("%w: invalid block ID %q", errUnsupportedTarget, blockID)
	}
	if owner, ok := existingBlockIDs(snapshot)[blockID]; ok && owner != projection.Ref.NodeID {
		return "", false, fmt.Errorf("%w: duplicate block ID %q", errUnsupportedTarget, blockID)
	}
	updated, err := setInlineField(snapshot, projection, field, []string{"^" + blockID})
	if err != nil {
		return "", false, err
	}
	return updated, true, nil
}

func preferredBlockIdentifierField(noteType *NoteType) *Field {
	if noteType == nil {
		return nil
	}
	for _, field := range noteType.Fields {
		if field == nil || field.Kind != FieldKindScalar || field.List {
			continue
		}
		if field.IsPreferredIdentifier {
			return field
		}
	}
	for _, field := range noteType.Fields {
		if field == nil || field.Kind != FieldKindScalar || field.List {
			continue
		}
		if field.IsIdentifier {
			return field
		}
	}
	return nil
}

func (op setBlockIDOp) apply(state *documentState) error {
	snapshot, projection, err := projectState(state, op.Ref)
	if err != nil {
		return err
	}
	if projection.Ref.Kind != NodeKindEmbedded {
		return nil
	}
	blockID := strings.TrimSpace(strings.TrimPrefix(op.BlockID, "^"))
	if !ValidBlockID(blockID) {
		return fmt.Errorf("%w: invalid block ID %q", errUnsupportedTarget, blockID)
	}
	node := snapshot.SectionsByID[projection.Ref.NodeID]
	if node == nil {
		return fmt.Errorf("%w: embedded node %s not found", errMissingNode, projection.Ref.String())
	}
	if strings.TrimPrefix(strings.TrimSpace(node.BlockID), "^") == blockID {
		return nil
	}
	if owner, ok := existingBlockIDs(snapshot)[blockID]; ok && owner != node.ID {
		return fmt.Errorf("%w: duplicate block ID %q", errUnsupportedTarget, blockID)
	}
	blockRange, ok := sectionBlockIDRange(snapshot.Content, node)
	if !ok {
		updated, _, err := EnsureBlockIDInSnapshot(snapshot, projection, blockID)
		if err != nil {
			return err
		}
		state.setContent(updated)
		return nil
	}
	state.setContent(replaceRange(snapshot.Content, blockRange, "^"+blockID))
	return nil
}

func (op removeBlockIDOp) apply(state *documentState) error {
	snapshot, projection, err := projectState(state, op.Ref)
	if err != nil {
		return err
	}
	if projection.Ref.Kind != NodeKindEmbedded && projection.Ref.Kind != NodeKindSection {
		return nil
	}
	node := snapshot.SectionsByID[projection.Ref.NodeID]
	if node == nil {
		return fmt.Errorf("%w: node %s not found", errMissingNode, projection.Ref.String())
	}
	if strings.TrimSpace(node.BlockID) == "" {
		return nil
	}
	// WHY: per SPEC-0023.US8, identifier-backed lines on derivable-identity
	// fields with populate: ON_LINK become opt-in linkability — when
	// the orphan-cleanup pass strips an unreferenced anchor, the source line
	// to delete is the whole `id:: ^...` line, not just the standalone
	// `^block-id` byte range that sectionBlockIDRange finds.
	if removed, ok, err := tryRemoveDerivableIdentifierLine(state, snapshot, projection, node); err != nil {
		return err
	} else if ok {
		state.setContent(removed)
		return nil
	}
	blockRange, ok := sectionBlockIDRange(snapshot.Content, node)
	if !ok {
		return nil
	}
	// Extend the range to consume the surrounding line so removing the anchor
	// does not leave a blank `^id`-shaped hole behind. Eat the leading newline
	// when the line is anchor-only and the trailing newline likewise. This
	// keeps source markdown clean across iterated cleanup runs.
	start, end := blockRange.Start, blockRange.End
	for end < len(snapshot.Content) && snapshot.Content[end] == ' ' {
		end++
	}
	if end < len(snapshot.Content) && snapshot.Content[end] == '\n' {
		end++
	}
	if start > 0 && snapshot.Content[start-1] == '\n' {
		// Only eat the preceding newline when the anchor sat on its own line;
		// otherwise we would join two unrelated content lines.
		preceding := snapshot.Content[:start-1]
		if idx := strings.LastIndexByte(preceding, '\n'); idx == -1 || strings.TrimSpace(preceding[idx+1:]) == "" {
			start--
		}
	}
	state.setContent(replaceRange(snapshot.Content, ByteRange{Start: start, End: end}, ""))
	return nil
}

// tryRemoveDerivableIdentifierLine deletes the authored `id:: ^...` line on a
// derivable-identity embedded node when the orphan-cleanup pass targets the
// node's preferred-identifier field. Returns (newContent, true, nil) when a
// derivable identifier line was found and removed, or (_, false, nil) when the
// node's anchor is sourced from a standalone `^block-id` and the caller should
// fall back to the legacy byte-range removal.
func tryRemoveDerivableIdentifierLine(state *documentState, snapshot *DocumentSnapshot, projection *NodeProjection, node *SectionNode) (string, bool, error) {
	if projection == nil || projection.Type == nil {
		return "", false, nil
	}
	field := preferredIdentifierField(projection.Type)
	if field == nil || !field.IsDerivableIdentifier || field.SourceKind != FieldSourceInline {
		return "", false, nil
	}
	binding, ok := projection.Fields[field.Name]
	if !ok || binding.Derived || len(binding.InlineSpans) == 0 {
		// Either the field is purely derived (no authored line to remove) or
		// the projection didn't surface a span to delete; either way nothing
		// to do via this path.
		return "", false, nil
	}
	span := binding.InlineSpans[0]
	start, end := span.LineRange.Start, span.LineRange.End
	if start < 0 || end <= start {
		return "", false, nil
	}
	// Walk back to consume the leading newline so the line removal does not
	// leave a blank line behind.
	if start > 0 && snapshot.Content[start-1] == '\n' {
		preceding := snapshot.Content[:start-1]
		if idx := strings.LastIndexByte(preceding, '\n'); idx == -1 || strings.TrimSpace(preceding[idx+1:]) == "" {
			start--
		}
	}
	// Walk forward through the line terminator.
	if end < len(snapshot.Content) && snapshot.Content[end] == '\n' {
		end++
	}
	updated := replaceRange(snapshot.Content, ByteRange{Start: start, End: end}, "")
	_ = state
	return updated, true, nil
}

func sameCollectionMembers(left, right []CollectionItem) bool {
	if len(left) != len(right) {
		return false
	}
	counts := make(map[string]int, len(left))
	for _, item := range left {
		counts[strings.TrimSpace(strings.TrimPrefix(item.Ref.Fragment, "#"))]++
	}
	for _, item := range right {
		key := strings.TrimSpace(strings.TrimPrefix(item.Ref.Fragment, "#"))
		counts[key]--
		if counts[key] < 0 {
			return false
		}
	}
	for _, count := range counts {
		if count != 0 {
			return false
		}
	}
	return true
}

var (
	errMissingNode       = fmt.Errorf("missing node")
	errMissingField      = fmt.Errorf("missing field")
	errCollectionDrift   = fmt.Errorf("collection drift")
	errUnsupportedTarget = fmt.Errorf("unsupported target")
)

func projectState(state *documentState, ref NodeRef) (*DocumentSnapshot, *NodeProjection, error) {
	if rootOnly, err := state.providerRootOnly(); err != nil {
		return nil, nil, err
	} else if rootOnly {
		if ref.Kind != NodeKindNote || strings.TrimSpace(ref.Fragment) != "" || strings.TrimSpace(ref.NodeID) != "" {
			return nil, nil, fmt.Errorf("%w: provider exposes only the note root", errUnsupportedTarget)
		}
		_, _, projection, err := state.projectProviderRoot(state.content)
		if err != nil {
			return nil, nil, err
		}
		return &DocumentSnapshot{
			NotePath: ref.NotePath, Content: state.content, ContentFingerprint: hashText(state.content),
		}, projection, nil
	}
	snapshot, err := state.documentSnapshot()
	if err != nil {
		return nil, nil, err
	}
	projection, err := projectSnapshot(snapshot, state.schema, ref, state.allowSelectorRecovery)
	if err != nil {
		return nil, nil, err
	}
	return snapshot, projection, nil
}

func (s *documentState) documentSnapshot() (*DocumentSnapshot, error) {
	if s.snapshot != nil && s.snapshotFor == s.content {
		return s.snapshot, nil
	}
	snapshot, err := BuildDocumentSnapshot(s.notePath, s.content, time.Time{})
	if err != nil {
		return nil, err
	}
	s.snapshot = snapshot
	s.snapshotFor = s.content
	return snapshot, nil
}

func projectSnapshot(snapshot *DocumentSnapshot, schema *Schema, ref NodeRef, allowSelectorRecovery bool) (*NodeProjection, error) {
	projection, err := ProjectNodeFromSnapshot(snapshot, schema, ref)
	if err != nil {
		return nil, err
	}
	if allowSelectorRecovery && projection.Type == nil && strings.TrimSpace(ref.TypeName) != "" {
		recovered, recoveryErr := ProjectNodeFromSnapshotWithSelectorRecovery(snapshot, schema, ref)
		if recoveryErr != nil {
			return nil, recoveryErr
		}
		if recovered.Type == nil {
			return nil, fmt.Errorf("missing selector-matched note projection for %s", ref.String())
		}
		projection = recovered
	}
	if err := validateResolvedProjectionRef(ref, projection.Ref); err != nil {
		return nil, err
	}
	return projection, nil
}

func setFrontmatterField(content string, field *Field, values []string, asLinks bool) (string, error) {
	if updated, ok, err := patchFrontmatterFieldSource(content, field, values, asLinks); err != nil {
		return "", err
	} else if ok {
		return updated, nil
	}
	doc, mapping, err := parseFrontmatterNode(content)
	if err != nil {
		return "", err
	}
	key := field.Source
	if key == "" {
		key = DefaultPropertyName(field.Name, PropertyCaseKebab)
	}
	encoded := make([]string, 0, len(values))
	for _, value := range values {
		if asLinks {
			encoded = append(encoded, strings.TrimSpace(value))
		} else {
			encoded = append(encoded, value)
		}
	}
	switch {
	case field.List:
		setYAMLSequenceValuePreservingStyle(mapping, key, encoded)
	case len(encoded) == 0:
		deleteYAMLMappingValue(mapping, key)
	default:
		setYAMLMappingValue(mapping, key, scalarYAMLNode(encoded[0]))
	}
	yamlText, err := encodeFrontmatterNode(doc)
	if err != nil {
		return "", err
	}
	fmRange := frontmatterRange(content)
	if fmRange.Len() == 0 {
		return "---\n" + yamlText + "---\n" + content, nil
	}
	return replaceRange(content, fmRange, "---\n"+yamlText+"---\n"), nil
}

func validateResolvedProjectionRef(requested NodeRef, resolved NodeRef) error {
	// WHY: author-facing locators may survive unrelated insertions, but replay
	// must stop when the resolved canonical node identity no longer matches the
	// captured operation. See [[ontology-edit-replay-conflict-contract]].
	// A note root is identified by its path; its structure fingerprint hashes
	// section byte offsets, so any earlier staged edit would move it.
	if requested.Kind == NodeKindNote && resolved.Kind == NodeKindNote {
		return nil
	}
	if requested.Structural != "" &&
		strings.TrimSpace(requested.Structural) != strings.TrimSpace(resolved.Structural) {
		if requested.Kind == NodeKindEmbedded && strings.TrimSpace(resolved.TypeName) != "" {
			if start, ok := sourceSpanStartFromFragment(normalizeSectionFragment(requested.Fragment, requested.NotePath)); ok && start == resolved.StartByte {
				return nil
			}
		}
		return fmt.Errorf("%w: structure changed for %s", errMissingNode, requested.String())
	}
	if requested.Structural == "" && requested.NodeID != "" &&
		strings.TrimSpace(requested.NodeID) != strings.TrimSpace(resolved.NodeID) {
		return fmt.Errorf("%w: node id changed for %s", errMissingNode, requested.String())
	}
	return nil
}

func parseFrontmatterNode(content string) (*yaml.Node, *yaml.Node, error) {
	fmRange := frontmatterRange(content)
	if fmRange.Len() == 0 {
		doc := &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{{Kind: yaml.MappingNode}}}
		return doc, doc.Content[0], nil
	}
	raw := content[fmRange.Start:fmRange.End]
	lines := strings.Split(raw, "\n")
	if len(lines) >= 2 {
		raw = strings.Join(lines[1:len(lines)-1], "\n")
	}
	doc := &yaml.Node{}
	if err := yaml.Unmarshal([]byte(raw), doc); err != nil {
		return nil, nil, err
	}
	if doc.Kind == 0 {
		doc = &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{{Kind: yaml.MappingNode}}}
	}
	if doc.Kind != yaml.DocumentNode {
		doc = &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{doc}}
	}
	if len(doc.Content) == 0 || doc.Content[0] == nil {
		doc.Content = []*yaml.Node{{Kind: yaml.MappingNode}}
	}
	if doc.Content[0].Kind != yaml.MappingNode {
		return nil, nil, fmt.Errorf("frontmatter is not a mapping")
	}
	return doc, doc.Content[0], nil
}

func encodeFrontmatterNode(doc *yaml.Node) (string, error) {
	var b strings.Builder
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return "", err
	}
	if err := enc.Close(); err != nil {
		return "", err
	}
	return strings.TrimPrefix(b.String(), "---\n"), nil
}

func yamlSequenceNode(values []string) *yaml.Node {
	node := &yaml.Node{Kind: yaml.SequenceNode}
	for _, value := range values {
		node.Content = append(node.Content, scalarYAMLNode(value))
	}
	return node
}

func scalarYAMLNode(value string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Value: value}
}

func setYAMLMappingValue(mapping *yaml.Node, key string, value *yaml.Node) {
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == key {
			mapping.Content[i+1] = value
			return
		}
	}
	mapping.Content = append(mapping.Content, scalarYAMLNode(key), value)
}

func deleteYAMLMappingValue(mapping *yaml.Node, key string) {
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == key {
			mapping.Content = append(mapping.Content[:i], mapping.Content[i+2:]...)
			return
		}
	}
}

func setInlineField(snapshot *DocumentSnapshot, projection *NodeProjection, field *Field, values []string) (string, error) {
	edits, err := inlineFieldEdits(snapshot, projection, field, values)
	if err != nil {
		return "", err
	}
	content := snapshot.Content
	for i := len(edits) - 1; i >= 0; i-- {
		content = replaceRange(content, edits[i].r, edits[i].replacement)
	}
	return content, nil
}

func unsetInlineField(snapshot *DocumentSnapshot, projection *NodeProjection, field *Field) (string, error) {
	if snapshot == nil || projection == nil || field == nil {
		return "", fmt.Errorf("%w: inline field projection is required", errMissingNode)
	}
	binding := projection.Fields[field.Name]
	if len(binding.InlineSpans) == 0 {
		return snapshot.Content, nil
	}
	content := snapshot.Content
	for index := len(binding.InlineSpans) - 1; index >= 0; index-- {
		span := binding.InlineSpans[index]
		rangeToRemove := inlineFieldEditRange(snapshot.Content, span)
		if !rangeToRemove.Valid(len(content)) {
			return "", fmt.Errorf("%w: invalid inline field range for %s", errCollectionDrift, field.Name)
		}
		content = replaceRange(content, rangeToRemove, "")
	}
	return content, nil
}

func inlineFieldEditRange(content string, span InlineFieldSpan) ByteRange {
	line, whole := span.LineRange, span.WholeRange
	if !line.Valid(len(content)) || !whole.Valid(len(content)) || whole.Start < line.Start || whole.End > line.End {
		return line
	}
	// Preserve surrounding prose and properties even when the schema does not declare them.
	if strings.TrimSpace(content[line.Start:whole.Start]) != "" || strings.TrimSpace(content[whole.End:line.End]) != "" {
		return whole
	}
	return line
}

func inlineFieldReplacementPrefix(content string, span InlineFieldSpan) string {
	if !span.LineRange.Valid(len(content)) || !span.KeyRange.Valid(len(content)) {
		return ""
	}
	if span.KeyRange.Start < span.LineRange.Start || span.KeyRange.Start > span.LineRange.End {
		return ""
	}
	prefix := content[span.LineRange.Start:span.KeyRange.Start]
	if isBulletInlinePropertyPrefix(prefix) {
		return prefix
	}
	return ""
}

func isBulletInlinePropertyPrefix(prefix string) bool {
	trimmed := strings.TrimSpace(prefix)
	return trimmed == "-" || trimmed == "*" || trimmed == "+"
}

func rangeStartsLine(content string, start int) bool {
	return start <= 0 || start > len(content) || content[start-1] == '\n'
}

func collectionInsertOffset(snapshot *DocumentSnapshot, parentProjection *NodeProjection, fieldName string) int {
	if collection, ok := parentProjection.Collections[fieldName]; ok && len(collection.Items) > 0 {
		return collection.Items[len(collection.Items)-1].Range.End
	}
	if parentProjection.Ref.Kind == NodeKindNote {
		return len(snapshot.Content)
	}
	return parentProjection.Ref.EndByte
}

func inlineInsertOffset(snapshot *DocumentSnapshot, projection *NodeProjection) int {
	if projection.Ref.Kind == NodeKindNote {
		return len(snapshot.Content)
	}
	node := snapshot.SectionsByID[projection.Ref.NodeID]
	if node == nil {
		return projection.Ref.EndByte
	}
	if strings.TrimSpace(node.BlockID) != "" {
		line := "\n^" + strings.TrimPrefix(node.BlockID, "^")
		if idx := strings.LastIndex(node.Content, line); idx >= 0 {
			return node.StartByte + idx
		}
	}
	return node.EndByte
}

func embeddedNodeNeedsBlockID(snapshot *DocumentSnapshot, projection *NodeProjection) bool {
	if projection == nil || projection.Ref.Kind != NodeKindEmbedded {
		return false
	}
	node := snapshot.SectionsByID[projection.Ref.NodeID]
	if node == nil {
		return false
	}
	return strings.TrimSpace(node.BlockID) == ""
}

func replaceRange(content string, r ByteRange, replacement string) string {
	if !r.Valid(len(content)) {
		return content
	}
	return content[:r.Start] + replacement + content[r.End:]
}

func conflictFromError(notePath string, op editOp, err error) ConflictReport {
	ref := ""
	field := ""
	kind := ConflictKindUnsupportedTarget
	switch typed := op.(type) {
	case setFieldOp:
		ref = typed.Ref.String()
		field = typed.Field
	case setRawFrontmatterListOp:
		ref = typed.Ref.String()
		field = typed.Field
	case setNarrativeOp:
		ref = typed.Ref.String()
	case insertNarrativeOp:
		ref = typed.Ref.String()
	case ensureBlockIDOp:
		ref = typed.Ref.String()
	case setBlockIDOp:
		ref = typed.Ref.String()
	case removeBlockIDOp:
		ref = typed.Ref.String()
	case addEmbeddedNodeOp:
		ref = typed.ParentRef.String()
		field = typed.Field
	case deleteNodeOp:
		ref = typed.Ref.String()
	case reorderCollectionOp:
		ref = typed.ParentRef.String()
		field = typed.Field
	case addSectionFieldOp:
		ref = typed.Ref.String()
		field = typed.FieldPath
	}
	switch {
	case strings.Contains(err.Error(), errMissingNode.Error()),
		strings.Contains(err.Error(), " not found in "):
		kind = ConflictKindMissingNode
	case strings.Contains(err.Error(), errMissingField.Error()):
		kind = ConflictKindMissingField
	case strings.Contains(err.Error(), errCollectionDrift.Error()):
		kind = ConflictKindCollectionDrift
	case strings.Contains(strings.ToLower(err.Error()), "source changed"):
		kind = ConflictKindSourceChanged
	default:
		kind = ConflictKindUnsupportedTarget
	}
	return ConflictReport{
		Kind:     kind,
		NotePath: notePath,
		NodeRef:  ref,
		Field:    field,
		Message:  err.Error(),
	}
}

func resolveNarrativeBlock(blocks []NodeBodyBlock, op setNarrativeOp) (*NodeBodyBlock, error) {
	// Docs: [[ontology-edit-replay-conflict-contract#^spec-0046-span-ownership]]
	// keeps narrative edits scoped to narrative body blocks instead of raw byte
	// ranges that might now contain inline fields or child sections.
	prev := normalizeNarrativeMarkdown(op.PreviousMarkdown)
	var exact *NodeBodyBlock
	candidates := make([]*NodeBodyBlock, 0)
	for i := range blocks {
		block := &blocks[i]
		if block.Kind != NodeBodyBlockKindNarrative {
			continue
		}
		if block.Range.Start == op.Range.Start && block.Range.End == op.Range.End {
			exact = block
		}
		if prev == "" || normalizeNarrativeMarkdown(block.Markdown) == prev {
			candidates = append(candidates, block)
		}
	}
	if exact != nil && (prev == "" || normalizeNarrativeMarkdown(exact.Markdown) == prev) {
		return exact, nil
	}
	if len(candidates) == 1 {
		return candidates[0], nil
	}
	if len(candidates) > 1 {
		best := candidates[0]
		bestDistance := absInt(best.Range.Start - op.Range.Start)
		for _, candidate := range candidates[1:] {
			distance := absInt(candidate.Range.Start - op.Range.Start)
			if distance < bestDistance {
				best = candidate
				bestDistance = distance
			}
		}
		return best, nil
	}
	if exact != nil {
		return exact, nil
	}
	return nil, fmt.Errorf("%w: narrative block not found for %s", errMissingNode, op.Ref.String())
}

func normalizeNarrativeMarkdown(markdown string) string {
	return strings.TrimRight(markdown, " \t\n")
}

func preserveNarrativeSuffix(raw, markdown string) string {
	trimmedRaw := strings.TrimRight(raw, " \t\n")
	suffix := raw[len(trimmedRaw):]
	return normalizeNarrativeMarkdown(markdown) + suffix
}

func absInt(value int) int {
	if value < 0 {
		return -value
	}
	return value
}
