type ConflictKind string

const (
	ConflictKindMissingNode       ConflictKind = "MISSING_NODE"
	ConflictKindMissingField      ConflictKind = "MISSING_FIELD"
	ConflictKindCollectionDrift   ConflictKind = "COLLECTION_DRIFT"
	ConflictKindUnsupportedTarget ConflictKind = "UNSUPPORTED_TARGET"
	ConflictKindFieldChanged      ConflictKind = "FIELD_CHANGED"
	ConflictKindSourceChanged     ConflictKind = "SOURCE_CHANGED"
)

type CommitOutcome string

const (
	CommitOutcomeCommitted  CommitOutcome = "committed"
	CommitOutcomeUnchanged  CommitOutcome = "unchanged"
	CommitOutcomeConflicted CommitOutcome = "conflicted"
	CommitOutcomeFailed     CommitOutcome = "failed"
)

// ConflictReport describes one commit-time replay failure for a staged edit.
type ConflictReport struct {
	Kind             ConflictKind `json:"kind"`
	OperationID      string       `json:"operationId,omitempty"`
	NotePath         string       `json:"notePath"`
	NodeRef          string       `json:"nodeRef,omitempty"`
	Field            string       `json:"field,omitempty"`
	ExpectedValue    string       `json:"expectedValue,omitempty"`
	CurrentValue     string       `json:"currentValue,omitempty"`
	CurrentValues    []string     `json:"currentValues,omitempty"`
	CurrentValueKind string       `json:"currentValueKind,omitempty"`
	ProposedValue    string       `json:"proposedValue,omitempty"`
	Message          string       `json:"message"`
}

// FileCommitPlan is the preview payload for one note touched by an edit session.
type FileCommitPlan struct {
	NotePath              string `json:"notePath"`
	BaseFingerprint       string `json:"baseFingerprint"`
	CurrentFingerprint    string `json:"currentFingerprint"`
	UpdatedFingerprint    string `json:"updatedFingerprint"`
	Diff                  string `json:"diff,omitempty"`
	Rebased               bool   `json:"rebased,omitempty"`
	HasMaterialChange     bool   `json:"hasMaterialChange"`
	UpdatedContentPreview string `json:"updatedContentPreview,omitempty"`
}

// CommitPlan previews all per-file text edits generated by a session.
type CommitPlan struct {
	Files []FileCommitPlan `json:"files"`
}

// CommitResult reports whether a staged edit plan was applied and whether replay rebased.
type CommitResult struct {
	Outcome   CommitOutcome    `json:"outcome"`
	Plan      CommitPlan       `json:"plan"`
	Conflicts []ConflictReport `json:"conflicts,omitempty"`
	Warnings  []string         `json:"warnings,omitempty"`
	Applied   bool             `json:"applied"`
	Rebased   bool             `json:"rebased"`
}

// CommitOptions controls how much preview payload replay should produce.
type CommitOptions struct {
	IncludeDiff                  bool
	IncludeUpdatedContentPreview bool
	// WriteLease borrows an actual vault writer acquisition from a larger mutation.
	// A nil lease makes Commit acquire and release its own lease.
	WriteLease *indexlock.Lease
}

type planOptions struct {
	CompareWithDisk              bool
	IncludeDiff                  bool
	IncludeUpdatedContentPreview bool
	CapturePreviewRefLineage     bool
}

// PreviewRefLineage records a canonical staged ref and the preview identity
// produced by applying that field edit within this session replay.
type PreviewRefLineage struct {
	Original NodeRef `json:"original"`
	Preview  NodeRef `json:"preview"`
}

// EditSession stages ontology-aware note edits and replays them into minimal text changes.
// Docs: [[ontology-edit-replay-conflict-contract#^spec-0046-operation-model]].
type EditSession struct {
	vaultDef              obsidian.VaultDefinition
	noteMgr               obsidian.NoteReader
	schema                *ontoschema.Schema
	formats               *noteformat.Runtime
	allowSelectorRecovery bool
	ops                   []editOp
	docs                  map[string]*documentState
}

type editOp interface {
	notePath() string
	apply(*documentState) error
	conflictTarget() (NodeRef, string)
	withCanonicalRef(NodeRef) editOp
}

type documentState struct {
	notePath                   string
	content                    string
	baseContent                string
	expectedCurrentFingerprint string
	originalContent            string
	baseSnapshot               *DocumentSnapshot
	schema                     *ontoschema.Schema
	formats                    *noteformat.Runtime
	allowSelectorRecovery      bool
	snapshot                   *DocumentSnapshot
	snapshotFor                string
	captureRefLineage          bool
	refLineage                 []PreviewRefLineage
	invalidRefStructural       map[string]bool
}

func (s *documentState) setContent(content string) {
	if s.content == content {
		return
	}
	s.content = content
	s.snapshot = nil
	s.snapshotFor = ""
}

