// RewriteFile stages a whole-file content replacement for the given note.
// This is the escape hatch for transformations that compute the full updated
// text outside the node-level op model.
func (s *EditSession) RewriteFile(notePath, newContent string) error {
	notePath = strings.TrimSpace(notePath)
	if notePath == "" {
		return fmt.Errorf("rewrite file: notePath is required")
	}
	return s.stage(rewriteFileOp{NotePathValue: notePath, NewContent: newContent})
}

// StageFileTransform stages a function that computes the new file content from
// the current in-plan content at apply time. This lets callers (like validate
// fix appliers) compose with earlier ops on the same file without freezing
// text at stage time. Transforms for different files may run concurrently while
// planning, so callers must make captured state concurrency-safe.
func (s *EditSession) StageFileTransform(notePath string, transform func(content string) (string, error)) error {
	notePath = strings.TrimSpace(notePath)
	if notePath == "" {
		return fmt.Errorf("transform file: notePath is required")
	}
	if transform == nil {
		return fmt.Errorf("transform file: transform is required")
	}
	return s.stage(transformFileOp{NotePathValue: notePath, Transform: transform})
}

// SetNarrative stages a source-preserving markdown replacement for one
// narrative body block within the target node.
func (s *EditSession) SetNarrative(ref NodeRef, rangeStart, rangeEnd int, previousMarkdown, markdown string) error {
	return s.stage(setNarrativeOp{
		Ref:              ref,
		Range:            ByteRange{Start: rangeStart, End: rangeEnd},
		PreviousMarkdown: previousMarkdown,
		Markdown:         markdown,
	})
}

// InsertNarrative inserts the first narrative block at the canonical body
// boundary owned by ref. It fails closed once that node has authored body
// content, allowing the caller to retry through SetNarrative instead.
func (s *EditSession) InsertNarrative(ref NodeRef, markdown string) error {
	if strings.TrimSpace(markdown) == "" {
		return nil
	}
	return s.stage(insertNarrativeOp{Ref: ref, Markdown: strings.TrimRight(markdown, " \t\n")})
}

// EnsureBlockID stages a source-preserving block ID insertion for an embedded node.
func (s *EditSession) EnsureBlockID(ref NodeRef, blockID string) error {
	op := ensureBlockIDOp{
		Ref:     ref,
		BlockID: strings.TrimSpace(strings.TrimPrefix(blockID, "^")),
	}
	for _, existing := range s.ops {
		typed, ok := existing.(ensureBlockIDOp)
		if !ok {
			continue
		}
		if typed.Ref.String() == op.Ref.String() && typed.Ref.NodeID == op.Ref.NodeID && typed.Ref.Structural == op.Ref.Structural && typed.BlockID == op.BlockID {
			return nil
		}
	}
	return s.stage(op)
}

// SetBlockID stages a source-preserving block ID replacement for an embedded node.
func (s *EditSession) SetBlockID(ref NodeRef, blockID string) error {
	return s.stage(setBlockIDOp{
		Ref:     ref,
		BlockID: strings.TrimSpace(strings.TrimPrefix(blockID, "^")),
	})
}

// RemoveBlockID stages a source-preserving deletion of an embedded node's
// `^block-id` anchor. Idempotent: if the node has no anchor the apply is a
// no-op. Coderefs: [[linkable-embedded-node-identifiers#^spec-0023-us4]]
func (s *EditSession) RemoveBlockID(ref NodeRef) error {
	return s.stage(removeBlockIDOp{Ref: ref})
}

func (s *EditSession) stage(op editOp) error {
	if s == nil {
		return fmt.Errorf("edit session is nil")
	}
	canonical, err := canonicalizeEditOp(op)
	if err != nil {
		return err
	}
	s.ops = append(s.ops, canonical)
	return nil
}

// Preview computes the current per-file diff without touching disk.
func (s *EditSession) Preview(ctx context.Context) (CommitPlan, error) {
	plan, _, err := s.plan(ctx, planOptions{IncludeDiff: true, IncludeUpdatedContentPreview: true})
	return plan, err
}

// PreviewWithRefLineage computes the current plan and the uniquely surviving
// field-edit identities produced by this session's own replay. Callers may use
// the lineage only for refs already resolved against this exact preview.
func (s *EditSession) PreviewWithRefLineage(ctx context.Context) (CommitPlan, []PreviewRefLineage, error) {
	plan, states, err := s.plan(ctx, planOptions{
		IncludeDiff:                  true,
		IncludeUpdatedContentPreview: true,
		CapturePreviewRefLineage:     true,
	})
	if err != nil {
		return plan, nil, err
	}
	lineage := make([]PreviewRefLineage, 0)
	for _, state := range states {
		lineage = append(lineage, state.refLineage...)
	}
	return plan, lineage, nil
}

// PreviewCurrent replays staged ops against current disk state without writing files.
// It surfaces safe rebases in the returned plan and reports typed conflicts
// when the underlying file changed in a way that invalidates staged assumptions.
func (s *EditSession) PreviewCurrent(ctx context.Context) (CommitPlan, []ConflictReport, error) {
	plan, _, conflicts, err := s.previewCurrent(ctx, false)
	return plan, conflicts, err
}

// PreviewCurrentWithRefLineage captures uniquely surviving field-edit refs
// during the same current-source replay used to authorize a commit. The caller
// may publish that lineage only after committing this exact plan.
func (s *EditSession) PreviewCurrentWithRefLineage(ctx context.Context) (CommitPlan, []PreviewRefLineage, []ConflictReport, error) {
	return s.previewCurrent(ctx, true)
}

func (s *EditSession) previewCurrent(ctx context.Context, captureLineage bool) (CommitPlan, []PreviewRefLineage, []ConflictReport, error) {
	plan, states, err := s.plan(ctx, planOptions{
		CompareWithDisk: true, IncludeDiff: true, IncludeUpdatedContentPreview: true,
		CapturePreviewRefLineage: captureLineage,
	})
	if err != nil {
		var conflictErr conflictListError
		if AsConflictList(err, &conflictErr) {
			return plan, nil, conflictErr.Conflicts, nil
		}
		return CommitPlan{}, nil, nil, err
	}
	var lineage []PreviewRefLineage
	for _, state := range states {
		lineage = append(lineage, state.refLineage...)
	}
	return plan, lineage, nil, nil
}

// Commit replays staged ops against current disk state and writes files when replay succeeds.
func (s *EditSession) Commit(ctx context.Context) (CommitResult, error) {
	return s.CommitWithOptions(ctx, CommitOptions{IncludeDiff: true, IncludeUpdatedContentPreview: true})
}

// CommitWithOptions replays staged ops against current disk state and writes files when replay succeeds.
func (s *EditSession) CommitWithOptions(ctx context.Context, opts CommitOptions) (CommitResult, error) {
	vaultPaths, err := paths.NewVaultPaths(s.vaultDef.BasePath())
	if err != nil {
		return CommitResult{Outcome: CommitOutcomeFailed}, err
	}
	if err := recoverInterruptedEditWrites(&vaultPaths, opts.VaultWriteLeaseHeld); err != nil {
		return CommitResult{Outcome: CommitOutcomeFailed}, err
	}
	plan, states, err := s.plan(ctx, planOptions{
		CompareWithDisk:              true,
		IncludeDiff:                  opts.IncludeDiff,
		IncludeUpdatedContentPreview: opts.IncludeUpdatedContentPreview,
	})
	if err != nil {
		var conflictErr conflictListError
		if AsConflictList(err, &conflictErr) {
			return CommitResult{
				Outcome:   CommitOutcomeConflicted,
				Plan:      plan,
				Conflicts: conflictErr.Conflicts,
				Applied:   false,
			}, nil
		}
		return CommitResult{}, err
	}
	if !planHasMaterialChange(plan) {
		return CommitResult{
			Outcome: CommitOutcomeUnchanged,
			Plan:    plan,
			Applied: false,
			Rebased: planHasRebased(plan),
		}, nil
	}
	for _, state := range states {
		rootOnly, formatErr := state.providerRootOnly()
		if formatErr != nil {
			return CommitResult{}, formatErr
		}
		if rootOnly {
			return CommitResult{}, fmt.Errorf("provider root metadata saves require the journaled application adapter")
		}
	}
	materialNotePaths := materialNotePathSet(plan)
	for notePath, state := range states {
		if state == nil || !materialNotePaths[notePath] {
			delete(states, notePath)
		}
	}
	committedResult := CommitResult{
		Outcome: CommitOutcomeCommitted,
		Plan:    plan,
		Applied: true,
		Rebased: planHasRebased(plan),
	}
	var completion *CommitCompletionArtifact
	if opts.CompletionArtifact != nil {
		completion, err = opts.CompletionArtifact(committedResult)
		if err != nil {
			return CommitResult{Outcome: CommitOutcomeFailed}, err
		}
	}
	writeErr := writeStatesAtomically(states, &vaultPaths, opts.TransactionID, completion, opts.VaultWriteLeaseHeld)
	if writeErr != nil {
		var warning publicationWarningError
		if errors.As(writeErr, &warning) {
			return CommitResult{
				Outcome:  CommitOutcomeCommitted,
				Plan:     plan,
				Warnings: []string{warning.Error()},
				Applied:  true,
				Rebased:  planHasRebased(plan),
			}, nil
		}
		var writeConflict writeConflictError
		if errors.As(writeErr, &writeConflict) {
			return CommitResult{
				Outcome: CommitOutcomeConflicted,
				Plan:    plan,
				Conflicts: []ConflictReport{{
					Kind:     ConflictKindSourceChanged,
					NotePath: writeConflict.notePath,
					Message:  writeConflict.Error(),
				}},
				Applied: false,
				Rebased: planHasRebased(plan),
			}, nil
		}
		return CommitResult{Outcome: CommitOutcomeFailed}, writeErr
	}
	return committedResult, nil
}

func (s *EditSession) plan(ctx context.Context, opts planOptions) (CommitPlan, map[string]*documentState, error) {
	if err := ctx.Err(); err != nil {
		return CommitPlan{}, nil, err
	}
	if s.noteMgr == nil {
		return CommitPlan{}, nil, fmt.Errorf("note reader is required")
	}
	grouped := make(map[string][]editOp)
	for _, op := range s.ops {
		canonical, err := canonicalizeEditOp(op)
		if err != nil {
			return CommitPlan{}, nil, err
		}
		notePath := canonical.notePath()
		grouped[notePath] = append(grouped[notePath], canonical)
	}
	pathsList := make([]string, 0, len(grouped))
	for notePath := range grouped {
		pathsList = append(pathsList, notePath)
	}
	sort.Strings(pathsList)

	plan := CommitPlan{Files: make([]FileCommitPlan, 0, len(pathsList))}
	states := make(map[string]*documentState, len(pathsList))
	conflicts := make([]ConflictReport, 0)
	jobs := make([]fileEditPlanJob, 0, len(pathsList))

	for index, notePath := range pathsList {
		baseState := s.docs[notePath]
		if baseState == nil {
			// Capture the base snapshot at first replay, not at op staging time.
			// Browser sessions that need restart recovery seed this explicitly via
			// RestoreBaseFingerprints so drift remains visible after restore.
			baseSnapshot, err := s.loadEditDocumentSnapshot(ctx, notePath)
			if err != nil {
				return plan, nil, err
			}
			baseState = &documentState{
				notePath:              notePath,
				content:               baseSnapshot.Content,
				baseContent:           baseSnapshot.Content,
				baseSnapshot:          baseSnapshot,
				schema:                s.schema,
				formats:               s.formats,
				allowSelectorRecovery: s.allowSelectorRecovery,
			}
			s.docs[notePath] = baseState
		}
		var currentSnapshot *DocumentSnapshot
		if opts.CompareWithDisk {
			var err error
			currentSnapshot, err = s.loadEditDocumentSnapshot(ctx, notePath)
			if err != nil {
				return plan, nil, err
			}
		}
		jobs = append(jobs, fileEditPlanJob{
			index:           index,
			notePath:        notePath,
			baseState:       baseState,
			currentSnapshot: currentSnapshot,
			ops:             grouped[notePath],
		})
	}

	results := s.planFiles(jobs, opts)
	for _, result := range results {
		if result.err != nil {
			return plan, nil, result.err
		}
		if result.conflict != nil {
			conflicts = append(conflicts, *result.conflict)
		}
		states[result.notePath] = result.state
		plan.Files = append(plan.Files, result.filePlan)
	}
	if len(conflicts) > 0 {
		return plan, nil, conflictListError{Conflicts: conflicts}
	}
	return plan, states, nil
}

type fileEditPlanJob struct {
	index           int
	notePath        string
	baseState       *documentState
	currentSnapshot *DocumentSnapshot
	ops             []editOp
}

type fileEditPlanResult struct {
	index    int
	notePath string
	state    *documentState
	filePlan FileCommitPlan
	conflict *ConflictReport
	err      error
}

const maxConcurrentFilePlans = 8

func (s *EditSession) planFiles(jobs []fileEditPlanJob, opts planOptions) []fileEditPlanResult {
	results := make([]fileEditPlanResult, len(jobs))
	if len(jobs) == 0 {
		return results
	}
	workerCount := min(len(jobs), maxConcurrentFilePlans)
	work := make(chan fileEditPlanJob)
	var wg sync.WaitGroup
	for range workerCount {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for job := range work {
				results[job.index] = s.planFile(job, opts)
			}
		}()
	}
	for _, job := range jobs {
		work <- job
	}
	close(work)
	wg.Wait()
	return results
}

func (s *EditSession) planFile(job fileEditPlanJob, opts planOptions) fileEditPlanResult {
	result := fileEditPlanResult{
		index:    job.index,
		notePath: job.notePath,
	}
	state := &documentState{
		notePath:              job.notePath,
		content:               job.baseState.baseContent,
		baseContent:           job.baseState.baseContent,
		baseSnapshot:          job.baseState.baseSnapshot,
		schema:                s.schema,
		formats:               s.formats,
		allowSelectorRecovery: s.allowSelectorRecovery,
		captureRefLineage:     opts.CapturePreviewRefLineage,
	}
	rebased := false
	currentFingerprint := job.baseState.baseSnapshot.ContentFingerprint
	currentContent := job.baseState.baseContent
	if opts.CompareWithDisk {
		if job.currentSnapshot == nil {
			result.err = fmt.Errorf("plan file %s: current snapshot is required when comparing with disk", job.notePath)
			return result
		}
		currentSnapshot := job.currentSnapshot
		currentFingerprint = currentSnapshot.ContentFingerprint
		currentContent = currentSnapshot.Content
		state.expectedCurrentFingerprint = currentFingerprint
		if currentSnapshot.ContentFingerprint != job.baseState.baseSnapshot.ContentFingerprint {
			// IMPORTANT: replay ops against current disk content for commit and
			// PreviewCurrent, but keep the original base fingerprint in the plan
			// so callers can report a safe rebase instead of pretending the file
			// was unchanged.
			state.setContent(currentSnapshot.Content)
			rebased = true
		}
	}
	if opts.CompareWithDisk {
		if conflict := fieldChangedConflict(job.baseState, state, job.ops); conflict != nil {
			result.conflict = conflict
		}
	}
	finish := func() fileEditPlanResult {
		result.state = state
		result.filePlan = FileCommitPlan{
			NotePath:           job.notePath,
			BaseFingerprint:    job.baseState.baseSnapshot.ContentFingerprint,
			CurrentFingerprint: currentFingerprint,
			UpdatedFingerprint: hashText(state.content),
			Rebased:            rebased,
			HasMaterialChange:  state.content != currentContent,
		}
		result.err = populatePlanPayload(&result.filePlan, state, opts)
		return result
	}
	if result.conflict != nil {
		return finish()
	}
	baseNoop := false
	baseReplayNoop := false
	if opts.CompareWithDisk && rebased && !hasExplicitFieldWitness(job.ops) {
		baseReplay := &documentState{
			notePath:              job.notePath,
			content:               job.baseState.baseContent,
			baseContent:           job.baseState.baseContent,
			baseSnapshot:          job.baseState.baseSnapshot,
			schema:                s.schema,
			formats:               s.formats,
			allowSelectorRecovery: s.allowSelectorRecovery,
		}
		baseNoop = true
		for _, op := range job.ops {
			if !editOpMatchesBase(baseReplay, op) {
				baseNoop = false
				break
			}
		}
		baseReplayOK := applyEditOps(baseReplay, job.ops) == nil
		baseReplayNoop = baseReplayOK && baseReplay.content == job.baseState.baseContent
	}
	if opts.CompareWithDisk && rebased && (baseNoop || baseReplayNoop) {
		state.setContent(currentContent)
		return finish()
	}
	if err := applyEditOps(state, job.ops); err != nil {
		conflict := conflictFromError(job.notePath, err.op, err.err)
		result.conflict = &conflict
	}
	return finish()
}

func hasExplicitFieldWitness(ops []editOp) bool {
	for _, rawOp := range ops {
		if op, ok := rawOp.(setFieldOp); ok && op.ExpectedCaptured {
			return true
		}
	}
	return false
}

func populatePlanPayload(filePlan *FileCommitPlan, state *documentState, opts planOptions) error {
	if opts.IncludeDiff {
		diffText, _, err := initdiff.GenerateUnifiedDiff(state.baseContent, state.content, state.notePath)
		if err != nil {
			return err
		}
		filePlan.Diff = diffText
	}
	if opts.IncludeUpdatedContentPreview {
		filePlan.UpdatedContentPreview = state.content
	}
	return nil
}

type editApplyError struct {
	op  editOp
	err error
}

func applyEditOps(state *documentState, ops []editOp) *editApplyError {
	for i := 0; i < len(ops); {
		if _, ok := ops[i].(setFieldOp); ok {
			start := i
			for i < len(ops) {
				if _, ok := ops[i].(setFieldOp); !ok {
					break
				}
				i++
			}
			if err := applySetFieldOps(state, ops[start:i]); err != nil {
				return err
			}
			continue
		}
		if rootOnly, err := state.providerRootOnly(); err != nil {
			return &editApplyError{op: ops[i], err: err}
		} else if rootOnly {
			return &editApplyError{op: ops[i], err: fmt.Errorf("%w: source format permits root metadata edits only", errUnsupportedTarget)}
		}
		if state.captureRefLineage && len(state.refLineage) > 0 {
			// Structural edits after a captured field target can delete, replace,
			// or manufacture an indistinguishable node. Refuse to carry lineage
			// across that boundary without stronger operation-specific evidence.
			state.refLineage = nil
		}
		var beforeStructural map[string]int
		if state.captureRefLineage {
			beforeStructural = documentStructuralCounts(state)
		}
		if err := ops[i].apply(state); err != nil {
			return &editApplyError{op: ops[i], err: err}
		}
		if state.captureRefLineage {
			state.recordStructuralInvalidations(beforeStructural, documentStructuralCounts(state), ops[i])
		}
		i++
	}
	return nil
}

func applySetFieldOps(state *documentState, ops []editOp) *editApplyError {
	if rootOnly, err := state.providerRootOnly(); err != nil {
		return &editApplyError{op: ops[0], err: err}
	} else if rootOnly {
		typed := make([]setFieldOp, len(ops))
		for index, op := range ops {
			typed[index] = op.(setFieldOp)
		}
		failed, applyErr := applyProviderRootFieldOps(state, typed)
		if applyErr != nil {
			if failed == nil {
				failed = ops[0]
			}
			return &editApplyError{op: failed, err: applyErr}
		}
		return nil
	}
	if len(ops) == 1 && !state.captureRefLineage {
		if err := ops[0].apply(state); err != nil {
			return &editApplyError{op: ops[0], err: err}
		}
		return nil
	}
	typed := make([]setFieldOp, 0, len(ops))
	for _, op := range ops {
		typed = append(typed, op.(setFieldOp))
	}
	updated, targets, edits, ok, failedOp, err := tryApplySetFieldOpsBatch(state, typed)
	if err != nil {
		return &editApplyError{op: failedOp, err: err}
	}
	if ok {
		state.setContent(updated)
		if state.captureRefLineage {
			captureFieldRefLineage(state, targets, edits)
		}
		return nil
	}
	bindings := make(map[NodeRef]NodeRef)
	for _, rawOp := range ops {
		original := rawOp.(setFieldOp)
		effective := original
		if rebound, exists := bindings[original.Ref]; exists {
			effective.Ref = rebound
		}
		_, projection, projectionErr := projectState(state, effective.Ref)
		if projectionErr != nil {
			return &editApplyError{op: rawOp, err: projectionErr}
		}
		before := projection.Ref
		if err := effective.apply(state); err != nil {
			return &editApplyError{op: rawOp, err: err}
		}
		preview, ok := fieldReplaySuccessor(state, before)
		if !ok {
			delete(bindings, original.Ref)
			continue
		}
		bindings[original.Ref] = preview
		recordFieldRefLineage(state, original.Ref, preview)
	}
	return nil
}

// fieldReplaySuccessor binds a node only after its original identity resolved
// strictly and this replay changed it. The pre-edit byte position is evidence
// local to that mutation; it is never used to recover an initially stale ref.
func fieldReplaySuccessor(state *documentState, before NodeRef) (NodeRef, bool) {
	snapshot, err := state.documentSnapshot()
	if err != nil {
		return NodeRef{}, false
	}
	resolver, err := newProjectionResolver(snapshot, state.schema)
	if err != nil {
		return NodeRef{}, false
	}
	preview, ok := replayRefAtStart(replayRefsByStart(resolver)[before.StartByte], before.Kind, before.TypeName)
	if !ok || (strings.TrimSpace(preview.Structural) == "" && strings.TrimSpace(preview.NodeID) == "") {
		return NodeRef{}, false
	}
	return preview, true
}

func recordFieldRefLineage(state *documentState, original, preview NodeRef) {
	if state == nil || !state.captureRefLineage || strings.TrimSpace(preview.Structural) == "" {
		return
	}
	if state.invalidRefStructural[strings.TrimSpace(original.Structural)] {
		return
	}
	for i := range state.refLineage {
		if state.refLineage[i].Original == original {
			state.refLineage[i].Preview = preview
			return
		}
	}
	state.refLineage = append(state.refLineage, PreviewRefLineage{Original: original, Preview: preview})
}

type contentEdit struct {
	r           ByteRange
	replacement string
	order       int
}

type fieldReplayTarget struct {
	Original NodeRef
	Before   NodeRef
}

func tryApplySetFieldOpsBatch(state *documentState, ops []setFieldOp) (string, []fieldReplayTarget, []contentEdit, bool, editOp, error) {
	snapshot, err := state.documentSnapshot()
	if err != nil {
		return "", nil, nil, false, ops[0], err
	}
	edits := make([]contentEdit, 0, len(ops))
	var targets []fieldReplayTarget
	if state.captureRefLineage {
		targets = make([]fieldReplayTarget, 0, len(ops))
	}
	for i, op := range ops {
		projection, err := projectSnapshot(snapshot, state.schema, op.Ref, state.allowSelectorRecovery)
		if err != nil {
			return "", nil, nil, false, op, err
		}
		field, err := validateSetFieldOperation(projection, op, state.schema, state.allowSelectorRecovery)
		if err != nil {
			return "", nil, nil, false, op, err
		}
		if op.Unset {
			return "", nil, nil, false, nil, nil
		}
		if state.captureRefLineage {
			targets = append(targets, fieldReplayTarget{Original: op.Ref, Before: projection.Ref})
		}
		opEdits, ok, err := setFieldBatchEdits(snapshot, projection, field, op)
		if err != nil {
			return "", nil, nil, false, op, err
		}
		if !ok {
			return "", nil, nil, false, nil, nil
		}
		for j := range opEdits {
			opEdits[j].order = i
			edits = append(edits, opEdits[j])
		}
	}
	if editsOverlap(edits) {
		return "", nil, nil, false, nil, nil
	}
	sort.SliceStable(edits, func(i, j int) bool {
		if edits[i].r.Start == edits[j].r.Start {
			return edits[i].order > edits[j].order
		}
		return edits[i].r.Start > edits[j].r.Start
	})
	content := snapshot.Content
	for _, edit := range edits {
		content = replaceRange(content, edit.r, edit.replacement)
	}
	return content, targets, edits, true, nil, nil
}

func captureFieldRefLineage(state *documentState, targets []fieldReplayTarget, edits []contentEdit) {
	if state == nil || !state.captureRefLineage || len(targets) == 0 {
		return
	}
	snapshot, err := state.documentSnapshot()
	if err != nil {
		return
	}
	resolver, err := newProjectionResolver(snapshot, state.schema)
	if err != nil {
		return
	}
	refsByStart := replayRefsByStart(resolver)
	starts := shiftedReplayTargetStarts(targets, edits)
	for i, target := range targets {
		if state.invalidRefStructural[strings.TrimSpace(target.Original.Structural)] {
			continue
		}
		preview, ok := replayRefAtStart(refsByStart[starts[i]], target.Before.Kind, target.Before.TypeName)
		if !ok || strings.TrimSpace(preview.Structural) == "" {
			continue
		}
		recordFieldRefLineage(state, target.Original, preview)
	}
}

func documentStructuralCounts(state *documentState) map[string]int {
	out := make(map[string]int)
	if state == nil {
		return out
	}
	snapshot, err := state.documentSnapshot()
	if err != nil {
		return out
	}
	resolver, err := newProjectionResolver(snapshot, state.schema)
	if err != nil {
		return out
	}
	for _, refs := range replayRefsByStart(resolver) {
		for _, ref := range refs {
			if structural := strings.TrimSpace(ref.Structural); structural != "" {
				out[structural]++
			}
		}
	}
	return out
}

func (state *documentState) recordStructuralInvalidations(before, after map[string]int, op editOp) {
	if state.invalidRefStructural == nil {
		state.invalidRefStructural = make(map[string]bool)
	}
	_, rewrite := op.(rewriteFileOp)
	_, transform := op.(transformFileOp)
	for structural, count := range before {
		afterCount := after[structural]
		if count > 0 && (count != 1 || afterCount != 1 || rewrite || transform) {
			state.invalidRefStructural[structural] = true
		}
	}
}

func replayRefsByStart(resolver *projectionResolver) map[int][]NodeRef {
	out := make(map[int][]NodeRef)
	for _, span := range resolver.snapshot.SourceSpans {
		if span == nil || span.Shape == EmbeddedSourceShapeSection {
			continue
		}
		out[span.Range.Start] = append(out[span.Range.Start], resolver.sourceSpanNodeRef(span))
	}
	var walk func([]*SectionNode)
	walk = func(nodes []*SectionNode) {
		for _, node := range nodes {
			if node == nil {
				continue
			}
			out[node.StartByte] = append(out[node.StartByte], resolver.sectionNodeRef(node))
			walk(node.Children)
		}
	}
	walk(resolver.snapshot.Sections)
	return out
}

func replayRefAtStart(refs []NodeRef, kind NodeKind, typeName string) (NodeRef, bool) {
	var found NodeRef
	for _, ref := range refs {
		if ref.Kind != kind || (strings.TrimSpace(typeName) != "" && ref.TypeName != typeName) {
			continue
		}
		if !found.IsZero() {
			return NodeRef{}, false
		}
		found = ref
	}
	return found, !found.IsZero()
}

func shiftedReplayTargetStarts(targets []fieldReplayTarget, edits []contentEdit) []int {
	type editDelta struct {
		end   int
		delta int
	}
	deltas := make([]editDelta, 0, len(edits))
	for _, edit := range edits {
		deltas = append(deltas, editDelta{end: edit.r.End, delta: len(edit.replacement) - edit.r.Len()})
	}
	sort.Slice(deltas, func(i, j int) bool { return deltas[i].end < deltas[j].end })
	order := make([]int, len(targets))
	for i := range targets {
		order[i] = i
	}
	sort.Slice(order, func(i, j int) bool {
		return targets[order[i]].Before.StartByte < targets[order[j]].Before.StartByte
	})
	out := make([]int, len(targets))
	deltaIndex, cumulative := 0, 0
	for _, targetIndex := range order {
		start := targets[targetIndex].Before.StartByte
		for deltaIndex < len(deltas) && deltas[deltaIndex].end <= start {
			cumulative += deltas[deltaIndex].delta
			deltaIndex++
		}
		out[targetIndex] = start + cumulative
	}
	return out
}

func editsOverlap(edits []contentEdit) bool {
	nonEmpty := make([]contentEdit, 0, len(edits))
	for _, edit := range edits {
		if edit.r.Len() == 0 {
			continue
		}
		nonEmpty = append(nonEmpty, edit)
	}
	sort.Slice(nonEmpty, func(i, j int) bool {
		return nonEmpty[i].r.Start < nonEmpty[j].r.Start
	})
	for i := 1; i < len(nonEmpty); i++ {
		if nonEmpty[i].r.Start < nonEmpty[i-1].r.End {
			return true
		}
	}
	return false
}

func setFieldBatchEdits(snapshot *DocumentSnapshot, projection *NodeProjection, field *Field, op setFieldOp) ([]contentEdit, bool, error) {
	if strings.EqualFold(op.Field, "title") {
		return titleBatchEdits(snapshot, projection, op.Values)
	}
	if field.SourceKind == FieldSourceCheckbox {
		return checkboxBatchEdits(snapshot, projection, field, op.Values)
	}
	if projection.Ref.Kind == NodeKindEmbedded && embeddedNodeNeedsBlockID(snapshot, projection) {
		return nil, false, nil
	}
	if field.SourceKind == FieldSourceInline {
		edits, err := inlineFieldEdits(snapshot, projection, field, op.Values)
		return edits, err == nil, err
	}
	return nil, false, nil
}

func titleBatchEdits(snapshot *DocumentSnapshot, projection *NodeProjection, values []string) ([]contentEdit, bool, error) {
	if len(values) != 1 {
		return nil, false, fmt.Errorf("%w: title expects one value", errUnsupportedTarget)
	}
	value := oneLineTitleValue(values[0])
	switch projection.Ref.Kind {
	case NodeKindEmbedded:
		if span := snapshot.SourceSpansByID[projection.Ref.NodeID]; span != nil &&
			(span.Shape == EmbeddedSourceShapeCheckboxItem || span.Shape == EmbeddedSourceShapeListItem) {
			edit, err := sourceSpanTitleEdit(snapshot, span, value)
			if err != nil {
				return nil, false, err
			}
			return []contentEdit{edit}, true, nil
		}
		return nil, false, nil
	default:
		return nil, false, nil
	}
}

func sourceSpanTitleEdit(snapshot *DocumentSnapshot, span *MarkdownSourceSpan, value string) (contentEdit, error) {
	if !span.ContentRange.Valid(len(snapshot.Content)) || span.ContentRange.Len() == 0 {
		return contentEdit{}, fmt.Errorf("%w: invalid title range", errCollectionDrift)
	}
	lineEnd := span.ContentRange.End
	if nextLine := strings.IndexByte(snapshot.Content[span.ContentRange.Start:span.ContentRange.End], '\n'); nextLine >= 0 {
		lineEnd = span.ContentRange.Start + nextLine
	}
	titleEnd := lineEnd
	for _, marker := range span.Markers {
		if marker.Range.Start >= span.ContentRange.Start && marker.Range.Start < titleEnd {
			titleEnd = marker.Range.Start
		}
	}
	for _, inline := range scanInlineFieldsInListSegment(snapshot.Content[span.ContentRange.Start:lineEnd], span.ContentRange.Start) {
		if inline.WholeRange.Start >= span.ContentRange.Start && inline.WholeRange.Start < titleEnd {
			titleEnd = inline.WholeRange.Start
		}
	}
	if tokenStart := trailingListMetadataTokenStart(snapshot.Content[span.ContentRange.Start:lineEnd], 0, lineEnd-span.ContentRange.Start); tokenStart >= 0 {
		absolute := span.ContentRange.Start + tokenStart
		if absolute < titleEnd {
			titleEnd = absolute
		}
	}
	titleEnd = trimSpaceLeftBounded(snapshot.Content, span.ContentRange.Start, titleEnd)
	if titleEnd < lineEnd && value != "" && snapshot.Content[titleEnd] != ' ' && snapshot.Content[titleEnd] != '\t' {
		value += " "
	}
	return contentEdit{r: ByteRange{Start: span.ContentRange.Start, End: titleEnd}, replacement: value}, nil
}

func checkboxBatchEdits(snapshot *DocumentSnapshot, projection *NodeProjection, field *Field, values []string) ([]contentEdit, bool, error) {
	if field.TypeName != "Boolean" || field.List || len(values) != 1 {
		return nil, false, nil
	}
	desired, err := parseCheckboxEditValue(values[0])
	if err != nil {
		return nil, false, err
	}
	span := snapshot.SourceSpansByID[projection.Ref.NodeID]
	if span == nil || span.Shape != EmbeddedSourceShapeCheckboxItem || span.Checkbox == nil {
		return nil, false, nil
	}
	r := span.Checkbox.TokenRange
	if !r.Valid(len(snapshot.Content)) || r.Len() != len("[ ]") {
		return nil, false, fmt.Errorf("%w: invalid checkbox token range for %s", errCollectionDrift, projection.Ref.String())
	}
	if span.Checkbox.Checked == desired {
		return nil, true, nil
	}
	token := "[ ]"
	if desired {
		token = "[x]"
	}
	return []contentEdit{{r: r, replacement: token}}, true, nil
}

func inlineFieldEdits(snapshot *DocumentSnapshot, projection *NodeProjection, field *Field, values []string) ([]contentEdit, error) {
	binding := projection.Fields[field.Name]
	propertyName := DefaultPropertyName(field.Name, projection.PropertyCase)
	lineText := propertyName + ":: " + strings.Join(values, ", ")
	if len(binding.InlineSpans) > 0 {
		edits := make([]contentEdit, 0, len(binding.InlineSpans))
		first := binding.InlineSpans[0]
		editRange := inlineFieldEditRange(snapshot.Content, first)
		replacement := inlineFieldReplacementPrefix(snapshot.Content, first) + lineText
		if editRange != first.LineRange {
			replacement = lineText
		} else if rangeStartsLine(snapshot.Content, first.LineRange.Start) {
			replacement += "\n"
		}
		edits = append(edits, contentEdit{r: editRange, replacement: replacement})
		for i := 1; i < len(binding.InlineSpans); i++ {
			edits = append(edits, contentEdit{r: inlineFieldEditRange(snapshot.Content, binding.InlineSpans[i])})
		}
		return edits, nil
	}
	insertAt := inlineInsertOffset(snapshot, projection)
	if insertAt < 0 || insertAt > len(snapshot.Content) {
		return nil, fmt.Errorf("%w: invalid inline insert offset for %s", errUnsupportedTarget, field.Name)
	}
	prefix := ""
	if insertAt > 0 && snapshot.Content[insertAt-1] != '\n' {
		prefix = "\n"
	}
	return []contentEdit{{r: ByteRange{Start: insertAt, End: insertAt}, replacement: prefix + lineText + "\n"}}, nil
}

func editOpMatchesBase(state *documentState, op editOp) bool {
	switch typed := op.(type) {
	case setFieldOp:
		return setFieldOpMatchesBase(state, typed)
	case reorderCollectionOp:
		return reorderCollectionOpMatchesBase(state, typed)
	default:
		return false
	}
}

func setFieldOpMatchesBase(state *documentState, op setFieldOp) bool {
	if state == nil {
		return false
	}
	rootOnly, err := state.providerRootOnly()
	if err != nil {
		return false
	}
	if op.RawRootMetadata || (rootOnly && op.Ref.Kind == NodeKindNote && strings.TrimSpace(op.Ref.Fragment) == "" && strings.TrimSpace(op.Ref.NodeID) == "") {
		values, kind, err := fieldValueForReplay(state, op)
		if err != nil {
			return false
		}
		return equalEditFieldValue(kind, values, fieldValueKindForOp(op), op.Values)
	}
	_, projection, err := projectState(state, op.Ref)
	if err != nil || projection == nil {
		return false
	}
	if strings.EqualFold(op.Field, "title") {
		return len(op.Values) == 1 && oneLineTitleValue(op.Values[0]) == projectedNodeTitle(projection)
	}
	binding, ok := projection.Fields[op.Field]
	if !ok {
		return false
	}
	if op.Unset {
		return !binding.Present
	}
	if !binding.Present {
		return false
	}
	if len(op.Values) != len(binding.Values) {
		return false
	}
	for i := range op.Values {
		if op.Values[i] != binding.Values[i] {
			return false
		}
	}
	return true
}

func fieldChangedConflict(baseState, currentState *documentState, ops []editOp) *ConflictReport {
	if baseState == nil || currentState == nil || len(ops) == 0 {
		return nil
	}
	for _, rawOp := range ops {
		op, ok := rawOp.(setFieldOp)
		if !ok {
			continue
		}
		expected := append([]string(nil), op.ExpectedValues...)
		expectedKind := op.ExpectedValueKind
		if !op.ExpectedCaptured {
			var err error
			expected, expectedKind, err = fieldValueForReplay(baseState, op)
			if err != nil {
				continue
			}
		}
		if !op.ExpectedCaptured && equalEditFieldValue(expectedKind, expected, fieldValueKindForOp(op), op.Values) {
			continue
		}
		current, currentKind, err := fieldValueForReplay(currentState, op)
		if err != nil || equalEditFieldValue(expectedKind, expected, currentKind, current) {
			continue
		}
		return &ConflictReport{
			Kind:             ConflictKindFieldChanged,
			NotePath:         op.Ref.NotePath,
			NodeRef:          op.Ref.String(),
			Field:            op.Field,
			ExpectedValue:    formatEditValues(expected),
			CurrentValue:     formatEditValues(current),
			CurrentValues:    append([]string(nil), current...),
			CurrentValueKind: currentKind,
			ProposedValue:    formatEditValues(op.Values),
			Message: fmt.Sprintf(
				"field %s changed: expected %q, current %q, proposed %q",
				op.Field,
				formatEditValues(expected),
				formatEditValues(current),
				formatEditValues(op.Values),
			),
		}
	}
	return nil
}

func fieldValueForReplay(state *documentState, op setFieldOp) ([]string, string, error) {
	rootOnly, err := state.providerRootOnly()
	if err != nil {
		return nil, "", err
	}
	if op.RawRootMetadata || (rootOnly && op.Ref.Kind == NodeKindNote && strings.TrimSpace(op.Ref.Fragment) == "" && strings.TrimSpace(op.Ref.NodeID) == "") {
		return providerRootFieldValueForReplay(state, op)
	}
	_, projection, err := projectState(state, op.Ref)
	if err != nil {
		return nil, "", err
	}
	if strings.EqualFold(op.Field, "title") {
		return []string{projectedNodeTitle(projection)}, "scalar", nil
	}
	if projection == nil || projection.Type == nil {
		return nil, "", fmt.Errorf("%w: node type is required", errMissingNode)
	}
	binding, ok := projection.Fields[op.Field]
	if !ok {
		return nil, "", fmt.Errorf("%w: field %s not found", errMissingField, op.Field)
	}
	if !binding.Present {
		return nil, "unset", nil
	}
	kind := "scalar"
	if op.IsLinks || op.RequireScalarList {
		kind = "list"
	}
	values := append([]string(nil), binding.Values...)
	if kind == "scalar" && len(values) == 0 {
		values = []string{""}
	}
	return values, kind, nil
}

func fieldValueKindForOp(op setFieldOp) string {
	if op.Unset {
		return "unset"
	}
	if op.IsLinks || op.RequireScalarList {
		return "list"
	}
	return "scalar"
}

func equalEditFieldValue(leftKind string, left []string, rightKind string, right []string) bool {
	return leftKind == rightKind && equalEditValues(left, right)
}

func equalEditValues(left, right []string) bool {
	if len(left) != len(right) {
		return false
	}
	for i := range left {
		if left[i] != right[i] {
			return false
		}
	}
	return true
}

func formatEditValues(values []string) string {
	return strings.Join(values, ", ")
}

func reorderCollectionOpMatchesBase(state *documentState, op reorderCollectionOp) bool {
	if state == nil {
		return false
	}
	_, projection, err := projectState(state, op.ParentRef)
	if err != nil || projection == nil {
		return false
	}
	collection, ok := projection.Collections[op.Field]
	if !ok || validateCollectionPermutation(collection.Items, op.OrderedFragments) != nil {
		return false
	}
	for i, fragment := range op.OrderedFragments {
		if strings.TrimSpace(strings.TrimPrefix(fragment, "#")) != strings.TrimSpace(strings.TrimPrefix(collection.Items[i].Ref.Fragment, "#")) {
			return false
		}
	}
	return true
}

func projectedNodeTitle(projection *NodeProjection) string {
	if projection == nil || projection.Snapshot == nil {
		return ""
	}
	if projection.Ref.Kind == NodeKindNote {
		if title, ok := projection.Snapshot.Frontmatter["title"].(string); ok && strings.TrimSpace(title) != "" {
			return title
		}
		for _, section := range projection.Snapshot.Sections {
			if section != nil && section.Level == SectionLevelH1 && strings.TrimSpace(section.Title) != "" {
				return section.Title
			}
		}
		return titleFromNotePath(projection.Ref.NotePath)
	}
	if span := projection.Snapshot.SourceSpansByID[projection.Ref.NodeID]; span != nil {
		return span.Title
	}
	if section := projection.Snapshot.SectionsByID[projection.Ref.NodeID]; section != nil {
		return section.Title
	}
	return ""
}

