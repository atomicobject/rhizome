func (op setFieldOp) apply(state *documentState) error {
	if op.RawRootMetadata {
		if op.Ref.Kind != NodeKindNote || strings.TrimSpace(op.Ref.Fragment) != "" || strings.TrimSpace(op.Ref.NodeID) != "" {
			return fmt.Errorf("%w: raw root metadata requires a note root", errUnsupportedTarget)
		}
		if op.Unset {
			updated, err := unsetFrontmatterField(state.content, &Field{
				Name: op.Field, Source: op.Field, SourceKind: FieldSourceFrontmatter,
				Kind: FieldKindScalar, TypeName: "String", List: true,
			})
			if err != nil {
				return err
			}
			state.setContent(updated)
			return nil
		}
		updated, err := setRawFrontmatterList(state.content, op.Field, op.Values)
		if err != nil {
			return err
		}
		state.setContent(updated)
		return nil
	}
	snapshot, projection, err := projectState(state, op.Ref)
	if err != nil {
		return err
	}
	field, err := validateSetFieldOperation(projection, op, state.schema, state.allowSelectorRecovery)
	if err != nil {
		return err
	}
	if strings.EqualFold(op.Field, "title") {
		updated, err := setNodeTitleField(snapshot, projection, op.Values)
		if err != nil {
			return err
		}
		state.setContent(updated)
		return nil
	}
	if op.Unset {
		var updated string
		switch {
		case field.SourceKind == FieldSourceCheckbox:
			updated, err = setCheckboxField(snapshot, projection, field, []string{"false"})
		case projection.Ref.Kind == NodeKindNote && field.SourceKind == FieldSourceFrontmatter:
			updated, err = unsetFrontmatterField(state.content, field)
		case field.SourceKind == FieldSourceInline:
			updated, err = unsetInlineField(snapshot, projection, field)
		default:
			err = fmt.Errorf("%w: unsupported field target %s", errUnsupportedTarget, op.Field)
		}
		if err != nil {
			return err
		}
		state.setContent(updated)
		return nil
	}
	if field.SourceKind == FieldSourceCheckbox {
		updated, err := setCheckboxField(snapshot, projection, field, op.Values)
		if err != nil {
			return err
		}
		state.setContent(updated)
		return nil
	}
	if projection.Ref.Kind == NodeKindEmbedded && embeddedNodeNeedsBlockID(snapshot, projection) {
		updated, _, err := EnsureBlockIDInSnapshot(snapshot, projection, "")
		if err != nil {
			return err
		}
		state.setContent(updated)
		updatedRef := op.Ref
		updatedRef.NodeID = ""
		updatedRef.Structural = ""
		updatedRef.StartByte = 0
		updatedRef.EndByte = 0
		snapshot, projection, err = projectState(state, updatedRef)
		if err != nil {
			return err
		}
	}
	var updated string
	switch {
	case projection.Ref.Kind == NodeKindNote && field.SourceKind == FieldSourceFrontmatter:
		updated, err = setFrontmatterField(state.content, field, op.Values, op.IsLinks)
	case field.SourceKind == FieldSourceInline:
		updated, err = setInlineField(snapshot, projection, field, op.Values)
	default:
		err = fmt.Errorf("%w: unsupported field target %s", errUnsupportedTarget, op.Field)
	}
	if err != nil {
		return err
	}
	state.setContent(updated)
	return nil
}

func fieldSupportsValueList(field *Field) bool {
	return field != nil && field.List && (field.Kind == FieldKindScalar || field.Kind == FieldKindEnum)
}

func validateSetFieldOperation(projection *NodeProjection, op setFieldOp, schema *Schema, allowIdentifierRepair bool) (*Field, error) {
	if projection == nil || projection.Type == nil {
		if strings.EqualFold(op.Field, "title") {
			return nil, nil
		}
		return nil, fmt.Errorf("%w: node %s has no resolved ontology type", errMissingNode, op.Ref.String())
	}
	field := projection.Type.ByName[op.Field]
	if field == nil && strings.EqualFold(op.Field, "title") {
		for name, candidate := range projection.Type.ByName {
			if strings.EqualFold(name, op.Field) {
				field = candidate
				break
			}
		}
	}
	if field == nil {
		if strings.EqualFold(op.Field, "title") {
			return nil, nil
		}
		return nil, fmt.Errorf("%w: field %s not found on %s", errMissingField, op.Field, projection.Ref.String())
	}
	if field.IsIdentifier && !allowIdentifierRepair {
		return nil, fmt.Errorf("%w: identifier field %s requires the graph-safe identifier rename workflow", errUnsupportedTarget, op.Field)
	}
	if op.RequireScalarList && !fieldSupportsValueList(field) {
		return nil, fmt.Errorf("%w: field %s is not a scalar or enum list", errUnsupportedTarget, op.Field)
	}
	if op.IsLinks && field.Kind != FieldKindLink {
		return nil, fmt.Errorf("%w: field %s is not a relation", errUnsupportedTarget, op.Field)
	}
	if !op.IsLinks && field.Kind == FieldKindLink {
		return nil, fmt.Errorf("%w: relation field %s requires a link edit", errUnsupportedTarget, op.Field)
	}
	if op.Unset {
		if field.Required {
			return nil, fmt.Errorf("%w: required field %s cannot be unset", errUnsupportedTarget, op.Field)
		}
		return field, nil
	}
	if err := validateEditFieldValues(field, op.Values, schema); err != nil {
		return nil, err
	}
	if op.IsLinks {
		for _, value := range op.Values {
			if strings.TrimSpace(value) == "" {
				return nil, fmt.Errorf("%w: relation field %s contains an empty target", errUnsupportedTarget, op.Field)
			}
		}
	}
	return field, nil
}

func setNodeTitleField(snapshot *DocumentSnapshot, projection *NodeProjection, values []string) (string, error) {
	if snapshot == nil || projection == nil {
		return "", fmt.Errorf("%w: title projection is required", errMissingNode)
	}
	if len(values) != 1 {
		return "", fmt.Errorf("%w: title expects one value", errUnsupportedTarget)
	}
	value := oneLineTitleValue(values[0])
	switch projection.Ref.Kind {
	case NodeKindNote:
		if _, ok := snapshot.Frontmatter["title"]; ok || snapshot.FrontmatterRange.Len() > 0 {
			return setFrontmatterField(snapshot.Content, &Field{Name: "title", Source: "title", SourceKind: FieldSourceFrontmatter, TypeName: "String"}, []string{value}, false)
		}
		return setNotePrimaryHeadingTitle(snapshot, value)
	case NodeKindSection:
		return setSectionHeadingTitle(snapshot, projection, value)
	case NodeKindEmbedded:
		if span := snapshot.SourceSpansByID[projection.Ref.NodeID]; span != nil {
			if span.Shape == EmbeddedSourceShapeSection {
				return setSectionHeadingTitle(snapshot, projection, value)
			}
			return setSourceSpanTitleField(snapshot, projection, value)
		}
		return setSectionHeadingTitle(snapshot, projection, value)
	default:
		return "", fmt.Errorf("%w: unsupported title target %s", errUnsupportedTarget, projection.Ref.String())
	}
}

func setNotePrimaryHeadingTitle(snapshot *DocumentSnapshot, value string) (string, error) {
	if snapshot == nil {
		return "", fmt.Errorf("%w: title projection is required", errMissingNode)
	}
	h1s := make([]*SectionNode, 0, 1)
	for _, node := range snapshot.Sections {
		if node != nil && node.Level == SectionLevelH1 {
			h1s = append(h1s, node)
		}
	}
	if len(h1s) != 1 {
		return "", fmt.Errorf("%w: note title requires title frontmatter or one H1", errUnsupportedTarget)
	}
	return replaceHeadingLineTitle(snapshot.Content, h1s[0].StartByte, value)
}

func setSectionHeadingTitle(snapshot *DocumentSnapshot, projection *NodeProjection, value string) (string, error) {
	if snapshot == nil || projection == nil {
		return "", fmt.Errorf("%w: title projection is required", errMissingNode)
	}
	if node := snapshot.SectionsByID[projection.Ref.NodeID]; node != nil {
		return replaceHeadingLineTitle(snapshot.Content, node.StartByte, value)
	}
	return "", fmt.Errorf("%w: heading title not found for %s", errMissingNode, projection.Ref.String())
}

func replaceHeadingLineTitle(content string, lineStart int, value string) (string, error) {
	if lineStart < 0 || lineStart >= len(content) {
		return "", fmt.Errorf("%w: invalid heading title range", errCollectionDrift)
	}
	lineEnd := len(content)
	if nextLine := strings.IndexByte(content[lineStart:], '\n'); nextLine >= 0 {
		lineEnd = lineStart + nextLine
	}
	line := content[lineStart:lineEnd]
	leading := 0
	for leading < len(line) && line[leading] == ' ' {
		leading++
	}
	hashes := leading
	for hashes < len(line) && line[hashes] == '#' {
		hashes++
	}
	if hashes == leading || hashes-leading > 6 {
		return "", fmt.Errorf("%w: target line is not a heading", errUnsupportedTarget)
	}
	titleStart := hashes
	for titleStart < len(line) && (line[titleStart] == ' ' || line[titleStart] == '\t') {
		titleStart++
	}
	titleEnd := trimHeadingTitleEnd(line, titleStart, len(line))
	if titleEnd < titleStart {
		titleEnd = titleStart
	}
	return replaceRange(content, ByteRange{Start: lineStart + titleStart, End: lineStart + titleEnd}, value), nil
}

func trimHeadingTitleEnd(line string, start, end int) int {
	end = trimSpaceLeftBounded(line, start, end)
	cursor := end - 1
	for cursor >= start && line[cursor] == '#' {
		cursor--
	}
	if cursor < end-1 {
		beforeHashes := trimSpaceLeftBounded(line, start, cursor+1)
		if beforeHashes < cursor+1 {
			return beforeHashes
		}
	}
	return end
}

func setSourceSpanTitleField(snapshot *DocumentSnapshot, projection *NodeProjection, value string) (string, error) {
	span := snapshot.SourceSpansByID[projection.Ref.NodeID]
	if span == nil || (span.Shape != EmbeddedSourceShapeCheckboxItem && span.Shape != EmbeddedSourceShapeListItem) {
		return "", fmt.Errorf("%w: unsupported title target %s", errUnsupportedTarget, projection.Ref.String())
	}
	if !span.ContentRange.Valid(len(snapshot.Content)) || span.ContentRange.Len() == 0 {
		return "", fmt.Errorf("%w: invalid title range for %s", errCollectionDrift, projection.Ref.String())
	}
	edit, err := sourceSpanTitleEdit(snapshot, span, value)
	if err != nil {
		return "", err
	}
	return replaceRange(snapshot.Content, edit.r, edit.replacement), nil
}

func oneLineTitleValue(value string) string {
	return strings.Join(strings.Fields(strings.ReplaceAll(value, "\n", " ")), " ")
}

func setCheckboxField(snapshot *DocumentSnapshot, projection *NodeProjection, field *Field, values []string) (string, error) {
	if snapshot == nil || projection == nil || field == nil {
		return "", fmt.Errorf("%w: checkbox projection is required", errMissingNode)
	}
	if field.TypeName != "Boolean" || field.List {
		return "", fmt.Errorf("%w: checkbox field %s must be a singular Boolean", errUnsupportedTarget, field.Name)
	}
	if len(values) != 1 {
		return "", fmt.Errorf("%w: checkbox field %s expects one value", errUnsupportedTarget, field.Name)
	}
	desired, err := parseCheckboxEditValue(values[0])
	if err != nil {
		return "", err
	}
	span := snapshot.SourceSpansByID[projection.Ref.NodeID]
	if span == nil || span.Shape != EmbeddedSourceShapeCheckboxItem || span.Checkbox == nil {
		return "", fmt.Errorf("%w: %s is not a checkbox item", errUnsupportedTarget, projection.Ref.String())
	}
	r := span.Checkbox.TokenRange
	if !r.Valid(len(snapshot.Content)) || r.Len() != len("[ ]") {
		return "", fmt.Errorf("%w: invalid checkbox token range for %s", errCollectionDrift, projection.Ref.String())
	}
	if span.Checkbox.Checked == desired {
		return snapshot.Content, nil
	}
	token := "[ ]"
	if desired {
		token = "[x]"
	}
	return replaceRange(snapshot.Content, r, token), nil
}

func parseCheckboxEditValue(value string) (bool, error) {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "true", "checked", "done", "x", "1":
		return true, nil
	case "false", "unchecked", "open", " ", "0":
		return false, nil
	default:
		return false, fmt.Errorf("%w: invalid checkbox value %q", errUnsupportedTarget, value)
	}
}

func (op addEmbeddedNodeOp) apply(state *documentState) error {
	snapshot, parentProjection, err := projectState(state, op.ParentRef)
	if err != nil {
		return err
	}
	field := parentProjection.Type.ByName[op.Field]
	if field == nil || field.Kind != FieldKindSection || !field.List {
		return fmt.Errorf("%w: collection %s not found on %s", errMissingField, op.Field, parentProjection.Ref.String())
	}
	childType := state.schema.Types[field.TypeName]
	if childType == nil || childType.Role != TypeRoleEmbeddedNode {
		return fmt.Errorf("%w: collection %s does not target embedded nodes", errUnsupportedTarget, op.Field)
	}
	blockID := strings.TrimSpace(strings.TrimPrefix(op.BlockID, "^"))
	if blockID == "" {
		blockID = slugBlockID(op.Heading)
	}
	if !ValidBlockID(blockID) {
		return fmt.Errorf("%w: invalid block ID %q", errUnsupportedTarget, blockID)
	}
	if owner, ok := existingBlockIDs(snapshot)[blockID]; ok && strings.TrimSpace(owner) != "" {
		return fmt.Errorf("%w: duplicate block ID %q", errUnsupportedTarget, blockID)
	}
	level := strings.Repeat("#", sectionLevelInt(field.SectionLevel))
	if level == "" {
		return fmt.Errorf("%w: collection %s has invalid section level", errUnsupportedTarget, op.Field)
	}
	snippet := strings.TrimRight(level+" "+strings.TrimSpace(op.Heading)+"\n"+strings.TrimSpace(op.Body)+"\n^"+blockID+"\n", "\n") + "\n"
	insertAt := collectionInsertOffset(snapshot, parentProjection, op.Field)
	if insertAt < 0 || insertAt > len(state.content) {
		return fmt.Errorf("%w: invalid insert offset for %s", errUnsupportedTarget, op.Field)
	}
	state.setContent(state.content[:insertAt] + snippet + state.content[insertAt:])
	return nil
}

func (op deleteNodeOp) apply(state *documentState) error {
	snapshot, projection, err := projectState(state, op.Ref)
	if err != nil {
		return err
	}
	if projection.Ref.Kind == NodeKindNote {
		return fmt.Errorf("%w: deleting full notes is out of scope", errUnsupportedTarget)
	}
	r := ByteRange{Start: projection.Ref.StartByte, End: projection.Ref.EndByte}
	if !r.Valid(len(snapshot.Content)) || r.Len() == 0 {
		return fmt.Errorf("%w: invalid node span for %s", errMissingNode, projection.Ref.String())
	}
	state.setContent(replaceRange(state.content, r, ""))
	return nil
}

func (op reorderCollectionOp) apply(state *documentState) error {
	snapshot, parentProjection, err := projectState(state, op.ParentRef)
	if err != nil {
		return err
	}
	collection, ok := parentProjection.Collections[op.Field]
	if !ok {
		return fmt.Errorf("%w: collection %s not found on %s", errMissingField, op.Field, parentProjection.Ref.String())
	}
	if err := validateCollectionPermutation(collection.Items, op.OrderedFragments); err != nil {
		return fmt.Errorf("%w: collection %s %v", errCollectionDrift, op.Field, err)
	}
	if state.baseSnapshot != nil {
		baseProjection, err := ProjectNodeFromSnapshot(state.baseSnapshot, state.schema, op.ParentRef)
		if err != nil {
			return err
		}
		baseCollection, ok := baseProjection.Collections[op.Field]
		if !ok {
			return fmt.Errorf("%w: collection %s not found on %s", errMissingField, op.Field, baseProjection.Ref.String())
		}
		if len(baseCollection.Items) == len(collection.Items) &&
			sameCollectionMembers(baseCollection.Items, collection.Items) &&
			baseCollection.OrderFingerprint != "" && collection.OrderFingerprint != "" &&
			baseCollection.OrderFingerprint != collection.OrderFingerprint {
			return fmt.Errorf("%w: collection %s order changed", errCollectionDrift, op.Field)
		}
	}
	itemByFragment := make(map[string]CollectionItem, len(collection.Items))
	blockByFragment := make(map[string]string, len(collection.Items))
	for _, item := range collection.Items {
		key := strings.TrimSpace(strings.TrimPrefix(item.Ref.Fragment, "#"))
		itemByFragment[key] = item
	}
	for i, item := range collection.Items {
		key := strings.TrimSpace(strings.TrimPrefix(item.Ref.Fragment, "#"))
		blockStart := item.Range.Start
		blockEnd := collection.Range.End
		if i+1 < len(collection.Items) {
			blockEnd = collection.Items[i+1].Range.Start
		}
		if blockEnd < blockStart || blockEnd > len(snapshot.Content) {
			return fmt.Errorf("%w: invalid member span for %s", errCollectionDrift, item.Ref.String())
		}
		blockByFragment[key] = snapshot.Content[blockStart:blockEnd]
	}
	ordered := make([]CollectionItem, 0, len(op.OrderedFragments))
	for _, fragment := range op.OrderedFragments {
		item, ok := itemByFragment[strings.TrimSpace(strings.TrimPrefix(fragment, "#"))]
		if !ok {
			return fmt.Errorf("%w: collection %s is missing %s", errCollectionDrift, op.Field, fragment)
		}
		ordered = append(ordered, item)
	}
	if !collection.Range.Valid(len(snapshot.Content)) || collection.Range.Len() == 0 {
		return fmt.Errorf("%w: collection %s has invalid range", errCollectionDrift, op.Field)
	}
	var b strings.Builder
	for _, item := range ordered {
		key := strings.TrimSpace(strings.TrimPrefix(item.Ref.Fragment, "#"))
		block, ok := blockByFragment[key]
		if !ok {
			return fmt.Errorf("%w: invalid member span for %s", errCollectionDrift, item.Ref.String())
		}
		b.WriteString(block)
	}
	state.setContent(replaceRange(state.content, collection.Range, b.String()))
	return nil
}

func validateCollectionPermutation(items []CollectionItem, orderedFragments []string) error {
	if len(items) != len(orderedFragments) {
		return fmt.Errorf("membership changed")
	}
	actual := make(map[string]struct{}, len(items))
	for _, item := range items {
		key := strings.TrimSpace(strings.TrimPrefix(item.Ref.Fragment, "#"))
		if key == "" {
			return fmt.Errorf("member has no stable fragment")
		}
		if _, exists := actual[key]; exists {
			return fmt.Errorf("member %q is duplicated", key)
		}
		actual[key] = struct{}{}
	}
	requested := make(map[string]struct{}, len(orderedFragments))
	for _, fragment := range orderedFragments {
		key := strings.TrimSpace(strings.TrimPrefix(fragment, "#"))
		if key == "" {
			return fmt.Errorf("requested member is empty")
		}
		if _, exists := requested[key]; exists {
			return fmt.Errorf("requested member %q is duplicated", key)
		}
		if _, exists := actual[key]; !exists {
			return fmt.Errorf("requested member %q is missing", key)
		}
		requested[key] = struct{}{}
	}
	if len(requested) != len(actual) {
		return fmt.Errorf("membership changed")
	}
	return nil
}

