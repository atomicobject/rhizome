// NewEditSession creates a library-first edit session over one vault.
func NewEditSession(vaultDef obsidian.VaultDefinition, noteMgr obsidian.NoteReader, schema *ontoschema.Schema) *EditSession {
	return &EditSession{
		vaultDef: vaultDef,
		noteMgr:  noteMgr,
		schema:   schema,
		docs:     map[string]*documentState{},
	}
}

// NewProviderAwareEditSession creates an edit session that dispatches root
// metadata operations through the configured source-format runtime.
func NewProviderAwareEditSession(vaultDef obsidian.VaultDefinition, noteMgr obsidian.NoteReader, schema *ontoschema.Schema, formats noteformat.Runtime) *EditSession {
	session := NewEditSession(vaultDef, noteMgr, schema)
	session.formats = &formats
	return session
}

// NewIdentifierRepairEditSession creates an edit session that may recover a
// selector-matched type after an identifier grammar change makes the ordinary
// typed projection unresolved. This authority is intentionally limited to a
// reviewed identifier-repair plan; general edit sessions remain fail-closed.
func NewIdentifierRepairEditSession(vaultDef obsidian.VaultDefinition, noteMgr obsidian.NoteReader, schema *ontoschema.Schema) *EditSession {
	session := NewEditSession(vaultDef, noteMgr, schema)
	session.allowSelectorRecovery = true
	return session
}

// RestoreBaseFingerprints seeds note-level base fingerprints for a replayed session.
// This is used when reconstructing a session from a serialized op snapshot after
// process restart: the current disk content becomes the replay base, while the
// restored fingerprint preserves whether the content drifted since the original
// client-backed session state. It cannot reconstruct field values changed before
// restoration; RestoreBases retains those stronger field-level witnesses.
func (s *EditSession) RestoreBaseFingerprints(ctx context.Context, fingerprints map[string]string) error {
	if len(fingerprints) == 0 {
		return nil
	}
	for notePath, fingerprint := range fingerprints {
		notePath = strings.TrimSpace(notePath)
		fingerprint = strings.TrimSpace(fingerprint)
		if notePath == "" || fingerprint == "" {
			continue
		}
		canonical, err := CanonicalEditPath(notePath)
		if err != nil {
			return err
		}
		notePath = canonical.String()
		snapshot, err := s.loadEditDocumentSnapshot(ctx, notePath)
		if err != nil {
			return err
		}
		baseSnapshot := *snapshot
		baseSnapshot.ContentFingerprint = fingerprint
		s.docs[notePath] = &documentState{
			notePath:              notePath,
			content:               snapshot.Content,
			baseContent:           snapshot.Content,
			baseSnapshot:          &baseSnapshot,
			schema:                s.schema,
			formats:               s.formats,
			allowSelectorRecovery: s.allowSelectorRecovery,
		}
	}
	return nil
}

// LoadNode resolves a node against current on-disk content without staging any edits.
func (s *EditSession) LoadNode(ctx context.Context, ref NodeRef) (*NodeProjection, error) {
	snapshot, err := s.loadEditDocumentSnapshot(ctx, ref.NotePath)
	if err != nil {
		return nil, err
	}
	state := &documentState{notePath: ref.NotePath, content: snapshot.Content, baseContent: snapshot.Content, baseSnapshot: snapshot, schema: s.schema, formats: s.formats}
	if rootOnly, rootErr := state.providerRootOnly(); rootErr != nil {
		return nil, rootErr
	} else if rootOnly {
		if ref.Kind != NodeKindNote || strings.TrimSpace(ref.Fragment) != "" || strings.TrimSpace(ref.NodeID) != "" {
			return nil, fmt.Errorf("%w: provider exposes only the note root", errUnsupportedTarget)
		}
		_, _, projection, projectErr := state.projectProviderRoot(snapshot.Content)
		return projection, projectErr
	}
	projection, err := ProjectNodeFromSnapshot(snapshot, s.schema, ref)
	if err != nil {
		return nil, err
	}
	if s.allowSelectorRecovery && projection.Type == nil && strings.TrimSpace(ref.TypeName) != "" {
		recovered, recoveryErr := ProjectNodeFromSnapshotWithSelectorRecovery(snapshot, s.schema, ref)
		if recoveryErr != nil {
			return nil, recoveryErr
		}
		if recovered.Type == nil {
			return nil, fmt.Errorf("missing selector-matched note projection for %s", ref.String())
		}
		projection = recovered
	}
	return projection, nil
}
