type parityNode struct {
	Ref         ontology.NodeRef
	Parent      ontology.NodeRef
	Fields      map[string]ontology.FieldBinding
	Collections map[string]ontology.CollectionBinding
	Body        []ontology.NodeBodyBlock
	Parts       []string
}

type parityResult struct {
	Nodes    []parityNode
	Catalog  readmodel.NodeReadModel
	Spans    []*ontology.MarkdownSourceSpan
	Chunks   OntologyNodeChunkSet
	Links    []noteformat.UnresolvedAuthoredLinkFact
	Locators *ontology.LinkTargetResult
}

// Expectations were captured before the SPEC-0133 parser move. They are literal
// compatibility evidence, never regenerated by this test.
func TestStructureParityBaseline(t *testing.T) {
	const fixtures = "../ontology/testdata/structure-parity"
	sdl, err := os.ReadFile(filepath.Join(fixtures, "schema.graphql"))
	require.NoError(t, err)
	root := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".rhizome/ontology"), 0755))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".rhizome/ontology/parity.graphql"), sdl, 0644))
	schema, err := ontoschema.LoadSchema(root)
	require.NoError(t, err)
	for _, name := range []string{"nested", "long-title", "fallback", "malformed", "unicode"} {
		t.Run(name, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(fixtures, name+".md"))
			require.NoError(t, err)
			path := "notes/" + name + ".md"
			if name == "fallback" {
				path = "other/fallback.md"
			}
			snapshot, err := ontology.BuildDocumentSnapshot(path, string(raw), time.Time{})
			require.NoError(t, err)
			projection, err := ontology.ProjectNodeFromSnapshot(snapshot, schema, ontology.NodeRef{NotePath: path, Kind: ontology.NodeKindNote})
			require.NoError(t, err)
			result := parityResult{Spans: snapshot.SourceSpans}
			result.Catalog, err = ontology.BuildIntelOntologyNodeReadModel(schema, projection, 123)
			require.NoError(t, err)
			result.Chunks, err = BuildOntologyNodeChunks(schema, projection, embeddings.ProviderConfig{Provider: "test", Model: "deterministic"}, 123)
			require.NoError(t, err)
			refs := []ontology.NodeRef{}
			for _, row := range result.Catalog.Nodes {
				var ref ontology.NodeRef
				require.NoError(t, json.Unmarshal([]byte(row.NodeRefJSON), &ref))
				refs = append(refs, ref)
				node, err := ontology.ProjectBoundNodeFromSnapshot(snapshot, schema, ref)
				require.NoError(t, err)
				parent := ontology.NodeRef{}
				if ref.Kind != ontology.NodeKindNote {
					var parentErr error
					parent, _, parentErr = ontology.SemanticParentRef(snapshot, schema, ref)
					if parentErr != nil {
						parent = ontology.NodeRef{Fragment: parentErr.Error()}
					}
				}
				result.Nodes = append(result.Nodes, parityNode{ref, parent, node.Fields, node.Collections, ontology.BuildNodeBody(node, schema), ontology.NodeBodyParts(node, 4096)})
			}
			runtime, err := builtin.NewRuntime()
			require.NoError(t, err)
			provider, ok := runtime.Provider("markdown")
			require.True(t, ok)
			source, err := noteformat.NewAuthoredSource(paths.NotePath(path), provider.Descriptor(), raw, 0)
			require.NoError(t, err)
			facts, err := runtime.Project(source)
			require.NoError(t, err)
			result.Links = facts.Facts.Links
			// Source-local owner attribution is additive; compare the pre-existing public link contract.
			for i := range result.Links {
				result.Links[i].Owner = ""
			}
			service := ontology.NodeLinkService{Schema: schema, NoteReader: &obsidian.Note{}, VaultDef: obsidian.VaultDefinition{Path: root}, LoadSnapshot: func(context.Context, string) (*ontology.DocumentSnapshot, error) { return snapshot, nil }}
			links, err := service.LinkTargets(context.Background(), ontology.LinkTargetRequest{Refs: refs, Ensure: ontology.EnsureLinkTargetNever})
			require.NoError(t, err)
			result.Locators = &links
			actual, err := json.MarshalIndent(result, "", "  ")
			require.NoError(t, err)
			actual = append(actual, '\n')
			golden := filepath.Join(fixtures, name+".golden.json")
			expected, err := os.ReadFile(golden)
			require.NoError(t, err)
			require.Equal(t, string(expected), string(actual))
		})
	}
}

func TestStructureParityHTMLRootOnly(t *testing.T) {
	runtime, err := builtin.NewRuntime()
	require.NoError(t, err)
	provider, ok := runtime.Provider("html")
	require.True(t, ok)
	raw := []byte("<h1>Root</h1><h2 id='child'>Only a DOM target</h2>")
	source, err := noteformat.NewAuthoredSource("notes/root.html", provider.Descriptor(), raw, 0)
	require.NoError(t, err)
	projected, err := runtime.Project(source)
	require.NoError(t, err)
	root, err := ontology.BuildRootDocumentSnapshot(notemeta.NoteSourceSnapshot{Path: "notes/root.html", Format: "html", RawSource: raw, Projection: projected})
	require.NoError(t, err)
	require.Nil(t, root.MarkdownStructure)
}
